from scipy.stats import f_oneway
import statistics

grouped = {"green":[], "blue":[], "red":[],"yellow":[]}

for item in data:
    grouped[item[0]].append(item[1])
    
f_stat, p_value = f_oneway(grouped['green'], grouped['blue'], grouped['red'], grouped['yellow'])

print("F-statistic:", f_stat)
print("p-value:", p_value)

for color in grouped.keys():
    data = grouped[color]
    print(f"\nStatistics for {color}:")
    
    # Calculate individual metrics
    summary_stats = {
        "Length (Count)": len(data),
        "Min": min(data),
        "Max": max(data),
        "Mean (Average)": statistics.mean(data),
        "Median": statistics.median(data),
        "Mode": statistics.mode(data),
        "Standard Deviation": statistics.stdev(data),
        "Variance": statistics.variance(data)
    }

    for stat, value in summary_stats.items():
        print(f"{stat}: {value:.2f}" if isinstance(value, float) else f"{stat}: {value}")


